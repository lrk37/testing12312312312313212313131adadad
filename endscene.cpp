void init_menu(IDirect3DDevice9* pDevice)
{
	ImGui::CreateContext();
	ImGuiIO& io = ImGui::GetIO();
	io.ConfigFlags = ImGuiConfigFlags_NoMouseCursorChange;

	// set default shit.
	{
		ImGui::SetColorEditOptions(
			ImGuiColorEditFlags_DisplayHex |
			ImGuiColorEditFlags_InputRGB |
			ImGuiColorEditFlags_AlphaPreview | 
			ImGuiColorEditFlags_NoTooltip | 
			ImGuiColorEditFlags_NoOptions |
			ImGuiColorEditFlags_AlphaBar |
			ImGuiColorEditFlags_NoSidePreview |
			ImGuiColorEditFlags_NoInputs 
		);

		ImFontConfig font_config;
		font_config.PixelSnapH = false;
		font_config.FontDataOwnedByAtlas = false;
		font_config.OversampleH = 2;
		font_config.OversampleV = 2;
		font_config.RasterizerMultiply = 1.5f;

		static const ImWchar ranges[] = {
			0x0020, 0x00FF, // Basic Latin + Latin Supplement
			0x0400, 0x052F, // Cyrillic + Cyrillic Supplement
			0x2DE0, 0x2DFF, // Cyrillic Extended-A
			0xA640, 0xA69F, // Cyrillic Extended-B
			0xE000, 0xE226, // icons
			0,
		};

		font_config.GlyphRanges = ranges;
		font_config.FontBuilderFlags |= ImGuiFreeTypeBuilderFlags_Monochrome | ImGuiFreeTypeBuilderFlags_MonoHinting;

		ImFont* tahoma = io.Fonts->AddFontFromFileTTF("C:\\Windows\\Fonts\\tahoma.ttf", 12, &font_config, font_config.GlyphRanges);
		io.FontDefault = tahoma;

		font_config.FontBuilderFlags = 0;

		g_GUI.cog = io.Fonts->AddFontFromMemoryTTF(&rawData, sizeof(rawData), 10, &font_config, font_config.GlyphRanges);
		ApplyStyle();
	}

	D3DDEVICE_CREATION_PARAMETERS param = {};
	pDevice->GetCreationParameters(&param);

	ImGui_ImplWin32_Init(param.hFocusWindow);
	ImGui_ImplDX9_Init(pDevice);
}

long __stdcall Hooks::Present(IDirect3DDevice9* pDevice, void* a1, void* a2, HWND a3, void* a4)
{
	if (!menu_initialized)
	{
		init_menu(pDevice);
		menu_initialized = true;

		g_input.key_states[ VK_INSERT ].toggled_state = true; // open dat bitty
	}

	DWORD colorwrite, srgbwrite;
	pDevice->GetRenderState( D3DRS_COLORWRITEENABLE, &colorwrite );
	pDevice->GetRenderState( D3DRS_SRGBWRITEENABLE, &srgbwrite );

	pDevice->SetRenderState( D3DRS_COLORWRITEENABLE, 0xffffffff );
	pDevice->SetRenderState( D3DRS_SRGBWRITEENABLE, false );

	ImGui_ImplDX9_NewFrame();
	ImGui_ImplWin32_NewFrame();
	ImGui::NewFrame();

	g_GUI.Render();

	ImGui::EndFrame();
	ImGui::Render();
	ImGui_ImplDX9_RenderDrawData(ImGui::GetDrawData());

	pDevice->SetRenderState( D3DRS_COLORWRITEENABLE, colorwrite );
	pDevice->SetRenderState( D3DRS_SRGBWRITEENABLE, srgbwrite );

	return g_hooks.m_device.GetOldMethod<decltype(&Present)>(17)(pDevice, a1, a2, a3, a4);
}